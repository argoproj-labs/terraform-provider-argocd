package testhelpers

import (
	"context"
	"encoding/base64"
	"fmt"
	"io"
	"log"
	"os/exec"
	"path/filepath"
	"strings"
	"time"

	"github.com/testcontainers/testcontainers-go"
	tcexec "github.com/testcontainers/testcontainers-go/exec"
	"github.com/testcontainers/testcontainers-go/modules/k3s"
	"github.com/testcontainers/testcontainers-go/wait"
	"k8s.io/client-go/rest"
	"k8s.io/client-go/tools/clientcmd"
)

const (
	// DefaultFileMode represents standard file permissions (0o644)
	DefaultFileMode = 0o644

	// DefaultDirMode represents standard permissions for copied directories (0o755)
	DefaultDirMode = 0o755

	// readyTimeout is how long we wait for each CRD / deployment to become ready. It has to be generous since it
	// includes pulling images from remote registries inside the k3s container.
	readyTimeout = "300s"

	// diagnoseTimeout bounds the collection of diagnostics after a failed wait; it uses its own context since the
	// original one may be the reason for the failure.
	diagnoseTimeout = 30 * time.Second
)

// K3sTestEnvironment represents a test environment with K3s and ArgoCD
type K3sTestEnvironment struct {
	K3sContainer *k3s.K3sContainer
	ArgoCDURL    string
	// AdminPassword is the password of the admin user, generated by Argo CD on startup
	AdminPassword string
	RESTConfig    *rest.Config
}

// SetupK3sWithArgoCD sets up a K3s cluster with ArgoCD using testcontainers
func SetupK3sWithArgoCD(ctx context.Context, argoCDVersion, k3sVersion string) (*K3sTestEnvironment, error) {
	log.Println("Setting up K3s test environment...")

	k3sContainer, err := k3s.Run(ctx,
		fmt.Sprintf("rancher/k3s:%s", k3sVersion),
		testcontainers.WithWaitStrategy(wait.ForLog("k3s is up and running")),
		testcontainers.WithExposedPorts("30123/tcp"),
	)
	if err != nil {
		return nil, fmt.Errorf("failed to start K3s container: %w", err)
	}

	config, err := k3sContainer.GetKubeConfig(ctx)
	if err != nil {
		return nil, fmt.Errorf("failed to get kubeconfig: %w", err)
	}

	restConfig, err := clientcmd.RESTConfigFromKubeConfig(config)
	if err != nil {
		return nil, fmt.Errorf("failed to get rest config: %w", err)
	}

	env := &K3sTestEnvironment{K3sContainer: k3sContainer, RESTConfig: restConfig}

	// Pull and preload Argo CD image in k3s to reduce waiting time during the `waitForArgoCD` step.
	argoCDImage := fmt.Sprintf("quay.io/argoproj/argocd:%s", argoCDVersion)

	log.Printf("Pre-pulling Argo CD image %s...\n", argoCDImage)

	// First, pull the image to ensure it exists locally
	_, err = testcontainers.GenericContainer(ctx, testcontainers.GenericContainerRequest{
		ContainerRequest: testcontainers.ContainerRequest{Image: argoCDImage},
		Started:          false, // Don't start the container, just pull the image
	})
	if err != nil {
		return nil, fmt.Errorf("failed to pull Argo CD image: %w", err)
	}

	// Now load the image into k3s
	err = k3sContainer.LoadImages(ctx, argoCDImage)
	if err != nil {
		return nil, fmt.Errorf("failed to preload Argo CD image: %w", err)
	}

	if err := env.installArgoCD(ctx, argoCDVersion); err != nil {
		env.Cleanup(ctx)
		return nil, fmt.Errorf("failed to install ArgoCD: %w", err)
	}

	log.Println("Waiting for ArgoCD CRDs to be established...")

	if err := env.waitForCRDs(ctx); err != nil {
		env.Cleanup(ctx)
		return nil, fmt.Errorf("failed to wait for ArgoCD CRDs: %w", err)
	}

	// The test data contains Argo CD custom resources, so it can only be applied once the CRDs are established
	log.Println("Applying test data...")

	if _, err := env.ExecInK3s(ctx, "kubectl", "apply", "-f", "/tmp/manifests/testdata"); err != nil {
		env.Cleanup(ctx)
		return nil, fmt.Errorf("failed to apply test data: %w", err)
	}

	log.Println("Waiting for ArgoCD to be ready...")

	if err := env.waitForArgoCD(ctx); err != nil {
		env.Cleanup(ctx)
		return nil, fmt.Errorf("failed to wait for ArgoCD: %w", err)
	}

	log.Println("ArgoCD ready!")

	return env, nil
}

// kustomizationTemplate is the root kustomization that is generated for the requested Argo CD version. It combines the
// upstream install manifests with our own resources (./install) and the patches that configure Argo CD for testing
// (./patches). The version is the only thing that differs between the Argo CD versions we test against.
const kustomizationTemplate = `apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
namespace: argocd
resources:
  - https://raw.githubusercontent.com/argoproj/argo-cd/%s/manifests/install.yaml
  - install
components:
  - patches
`

// installArgoCD copies the manifests directory into the K3s container, generates a kustomization for the given Argo CD
// version and applies it. The test data in the manifests directory is applied separately once the CRDs are established.
func (env *K3sTestEnvironment) installArgoCD(ctx context.Context, version string) error {
	rootDir, err := env.projectRoot()
	if err != nil {
		return fmt.Errorf("failed to find project root: %w", err)
	}

	// CopyDirToContainer places the directory inside the parent of the given path, so this ends up as /tmp/manifests
	if err = env.K3sContainer.CopyDirToContainer(ctx, filepath.Join(rootDir, "manifests"), "/tmp/manifests", DefaultDirMode); err != nil {
		return fmt.Errorf("failed to copy manifests to container: %w", err)
	}

	kustomization := []byte(fmt.Sprintf(kustomizationTemplate, version))
	if err = env.K3sContainer.CopyToContainer(ctx, kustomization, "/tmp/manifests/kustomization.yaml", DefaultFileMode); err != nil {
		return fmt.Errorf("failed to copy kustomization to container: %w", err)
	}

	log.Printf("Applying kustomization for Argo CD %s...\n", version)

	if _, err = env.ExecInK3s(ctx, "kubectl", "apply", "-k", "/tmp/manifests", "--server-side", "--force-conflicts"); err != nil {
		return err
	}

	return nil
}

// projectRoot gets the project root directory by checking `go env GOMOD`
func (env *K3sTestEnvironment) projectRoot() (string, error) {
	cmd := exec.Command("go", "env", "GOMOD")

	output, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("failed to find project root: %w", err)
	}

	return filepath.Dir(strings.TrimSpace(string(output))), nil
}

func (env *K3sTestEnvironment) ExecInK3s(ctx context.Context, args ...string) ([]byte, error) {
	concat := strings.Join(args, " ")
	// Multiplexed strips Docker's stream headers from the output (and merges stdout and stderr)
	exitCode, reader, err := env.K3sContainer.Exec(ctx, args, tcexec.Multiplexed())
	if err != nil {
		return []byte{}, fmt.Errorf("failed to exec '%s': %w", concat, err)
	}

	output, err := io.ReadAll(reader)
	if err != nil {
		return []byte{}, fmt.Errorf("failed to read kubectl output: %w", err)
	}

	if exitCode != 0 {
		return output, fmt.Errorf("'%s' failed with exit code %d: %s", concat, exitCode, string(output))
	}

	return output, nil
}

// waitForCRDs waits for the Argo CD CRDs to be established
func (env *K3sTestEnvironment) waitForCRDs(ctx context.Context) error {
	crds := []string{
		"applications.argoproj.io",
		"applicationsets.argoproj.io",
		"appprojects.argoproj.io",
	}

	for _, crd := range crds {
		if _, err := env.ExecInK3s(ctx, "kubectl", "wait", "--for=condition=Established", fmt.Sprintf("crd/%s", crd), "--timeout="+readyTimeout); err != nil {
			//nolint:contextcheck // diagnose deliberately uses a fresh context since ctx may be the reason for the failure
			return fmt.Errorf("failed to wait for CRD %s: %w\n%s", crd, err, env.diagnose(""))
		}
	}

	return nil
}

// waitForArgoCD waits for ArgoCD components to be ready and retrieves the admin password and URL
func (env *K3sTestEnvironment) waitForArgoCD(ctx context.Context) error {
	// Wait for deployments to be ready
	deployments := []string{"argocd-server", "argocd-repo-server", "argocd-redis", "private-git-repository"}

	for _, deployment := range deployments {
		if _, err := env.ExecInK3s(ctx, "kubectl", "wait", "--for=condition=available", fmt.Sprintf("deployment/%s", deployment), "-n", "argocd", "--timeout="+readyTimeout); err != nil {
			//nolint:contextcheck // diagnose deliberately uses a fresh context since ctx may be the reason for the failure
			return fmt.Errorf("failed to wait for deployment %s: %w\n%s", deployment, err, env.diagnose(deployment))
		}
	}

	// Argo CD generates the password of the admin user on startup and stores it in this secret
	if _, err := env.ExecInK3s(ctx, "kubectl", "wait", "--for=create", "secret/argocd-initial-admin-secret", "-n", "argocd", "--timeout="+readyTimeout); err != nil {
		//nolint:contextcheck // diagnose deliberately uses a fresh context since ctx may be the reason for the failure
		return fmt.Errorf("failed to wait for admin secret: %w\n%s", err, env.diagnose("argocd-server"))
	}

	encoded, err := env.ExecInK3s(ctx, "kubectl", "get", "secret", "argocd-initial-admin-secret", "-n", "argocd", "-o", "jsonpath={.data.password}")
	if err != nil {
		return fmt.Errorf("failed to get admin password: %w", err)
	}

	password, err := base64.StdEncoding.DecodeString(strings.TrimSpace(string(encoded)))
	if err != nil {
		return fmt.Errorf("failed to decode admin password: %w", err)
	}

	env.AdminPassword = string(password)

	localPort, err := env.K3sContainer.MappedPort(ctx, "30123")
	if err != nil {
		return fmt.Errorf("failed to setup port forward: %w", err)
	}

	env.ArgoCDURL = fmt.Sprintf("127.0.0.1:%s", localPort.Port())

	return nil
}

// diagnose collects cluster state after a failed wait so that flakes (image pulls, scheduling, resource pressure) can
// be root-caused from the logs. It is best effort: failing commands are included in the output instead of aborting.
// If deployment is empty only cluster-wide information is collected.
func (env *K3sTestEnvironment) diagnose(deployment string) string {
	ctx, cancel := context.WithTimeout(context.Background(), diagnoseTimeout)
	defer cancel()

	cmds := [][]string{
		{"kubectl", "-n", "argocd", "get", "pods", "-o", "wide"},
		{"kubectl", "-n", "argocd", "get", "events", "--sort-by=.lastTimestamp"},
		{"kubectl", "top", "nodes"},
	}

	if deployment != "" {
		cmds = append(cmds,
			[]string{"kubectl", "-n", "argocd", "describe", "deployment", deployment},
			[]string{"kubectl", "-n", "argocd", "describe", "pods", "-l", "app.kubernetes.io/name=" + deployment},
		)
	}

	var b strings.Builder

	b.WriteString("=== diagnostics ===\n")

	for _, c := range cmds {
		out, err := env.ExecInK3s(ctx, c...)
		fmt.Fprintf(&b, "\n--- %s ---\n%s\n", strings.Join(c, " "), out)

		if err != nil && len(out) == 0 {
			fmt.Fprintf(&b, "(command failed: %v)\n", err)
		}
	}

	return b.String()
}

// GetEnvironmentVariables returns the environment variables needed for tests
func (env *K3sTestEnvironment) GetEnvironmentVariables() map[string]string {
	return map[string]string{
		"ARGOCD_SERVER":        env.ArgoCDURL,
		"ARGOCD_AUTH_USERNAME": "admin",
		"ARGOCD_AUTH_PASSWORD": env.AdminPassword,
		// Argo CD serves a self-signed certificate
		"ARGOCD_INSECURE": "true",
	}
}

// Cleanup cleans up the test environment
func (env *K3sTestEnvironment) Cleanup(ctx context.Context) {
	// Terminate container
	if env.K3sContainer != nil {
		if err := env.K3sContainer.Terminate(ctx); err != nil {
			fmt.Printf("Warning: failed to terminate container: %v\n", err)
		}
	}
}
